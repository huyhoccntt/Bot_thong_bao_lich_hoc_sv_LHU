create table if not exists public.class_schedules (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    schedule_id text not null,
    study_date date not null,
    start_time time not null,
    end_time time not null,
    room text,
    campus text,
    class_code text,
    subject text,
    periods text,
    lesson_type text,
    teacher text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (user_id, schedule_id)
);

alter table public.class_schedules enable row level security;

drop policy if exists "Users can view their own schedules" on public.class_schedules;
create policy "Users can view their own schedules"
on public.class_schedules for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can insert their own schedules" on public.class_schedules;
create policy "Users can insert their own schedules"
on public.class_schedules for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can update their own schedules" on public.class_schedules;
create policy "Users can update their own schedules"
on public.class_schedules for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);
